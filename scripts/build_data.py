"""Generate data.js (student ID -> mentor) from the tutors spreadsheet.

Usage: python scripts/build_data.py path/to/QE_Tutors.xlsx

Only the student number, study year and mentor name are written out;
student names and e-mails stay in the spreadsheet.
"""
import json
import sys
from pathlib import Path

import openpyxl

OUT = Path(__file__).resolve().parent.parent / "data.js"


def main(xlsx_path):
    wb = openpyxl.load_workbook(xlsx_path, read_only=True, data_only=True)
    mentors = {}
    for ws in wb.worksheets:
        header_row, cols = None, {}
        for i, row in enumerate(ws.iter_rows(values_only=True), start=1):
            if header_row is None:
                labels = [str(c).strip().lower() if c else "" for c in row]
                if "student no." in labels and "tutor" in labels:
                    header_row = i
                    cols = {"id": labels.index("student no."), "tutor": labels.index("tutor")}
                continue
            student_id, tutor = row[cols["id"]], row[cols["tutor"]]
            if student_id is None or not tutor:
                continue
            student_id = str(student_id).strip().split(".")[0]
            if student_id in mentors:
                print(f"warning: duplicate student no. {student_id}", file=sys.stderr)
            mentors[student_id] = {"mentor": " ".join(str(tutor).split()), "year": ws.title.strip()}
        if header_row is None:
            print(f"warning: no header row found in sheet {ws.title!r}", file=sys.stderr)

    OUT.write_text(
        "// Generated by scripts/build_data.py - do not edit by hand.\n"
        "window.MENTORS = " + json.dumps(mentors, ensure_ascii=False, indent=1, sort_keys=True) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(mentors)} students to {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
